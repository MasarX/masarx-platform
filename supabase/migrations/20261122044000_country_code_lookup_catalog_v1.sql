INSERT INTO public.lookup_values (
  lookup_definition_id,
  value,
  label,
  description,
  sort_order,
  is_default,
  status,
  metadata
)
SELECT
  ld.id,
  seed.value,
  seed.label,
  'Canonical ISO alpha-2 country option for shipment and address workflows.',
  seed.sort_order,
  seed.is_default AND NOT EXISTS (
    SELECT 1 FROM public.lookup_values current_value
    WHERE current_value.lookup_definition_id = ld.id
      AND current_value.status = 'active' AND current_value.is_default
  ),
  'active',
  jsonb_build_object('standard', 'iso_3166_1_alpha_2')
FROM public.lookup_definitions ld
JOIN seed
  ON TRUE
WHERE ld.category = 'country_code'
ON CONFLICT (lookup_definition_id, value) DO NOTHING;
