-- Migration: Backfill workflow linkage for outbound_calls
-- Purpose: Create workflow_runs/steps for legacy outbound jobs that bypassed the engine.
-- Date: 2025-11-14

BEGIN;

-- Canonical template for legacy outbound job backfill
WITH upsert_template AS (
    INSERT INTO workflow_templates (
        id,
        name,
        description,
        version,
        status,
        scope_type,
        scope_id,
        notes
    )
    VALUES (
        '99990000-0000-0000-0000-000000350000',
        'legacy_outbound_job_wrapper_v1',
        'Backfill template used to attach legacy outbound_calls rows to workflow history.',
        1,
        'active',
        'global',
        NULL,
        'Auto-generated by legacy backfill migration.'
    )
    ON CONFLICT (name) DO UPDATE
        SET status = 'active',
            notes = EXCLUDED.notes,
            updated_at = workflow_now()
    RETURNING id
)
SELECT id FROM upsert_template
UNION ALL
SELECT id
FROM workflow_templates
WHERE name = 'legacy_outbound_job_wrapper_v1'
LIMIT 1;

INSERT INTO workflow_template_steps (
    id,
    workflow_template_id,
    sequence_order,
    operation_name,
    operation_settings_category,
    transition_condition,
    enabled,
    metadata,
    handler_key,
    handler_version
)
VALUES (
    '99990000-0000-0000-0000-000000350101',
    '99990000-0000-0000-0000-000000350000',
    1,
    'legacy_outbound_job',
    'operation_template',
    'success',
    FALSE,
    jsonb_build_object('catalog', 'legacy_outbound_job'),
    'outbound_http',
    'v1'
)
ON CONFLICT (id) DO UPDATE
    SET handler_key = EXCLUDED.handler_key,
        handler_version = EXCLUDED.handler_version,
        metadata = EXCLUDED.metadata;

DO $$
DECLARE
    v_job RECORD;
    v_run_id UUID;
    v_step_id UUID;
    v_step_status TEXT;
    v_run_status TEXT;
    v_operation_started_at TIMESTAMPTZ;
    v_operation_completed_at TIMESTAMPTZ;
    v_duration_ms INT;
    v_now TIMESTAMPTZ := now();
    v_context JSONB;
    v_step_result JSONB;
    v_failure_reason TEXT;
    v_last_error JSONB;
BEGIN
    FOR v_job IN
        SELECT *
        FROM outbound_calls
        WHERE workflow_run_step_id IS NULL
        ORDER BY created_at ASC
    LOOP
        v_run_id := gen_random_uuid();
        v_step_id := gen_random_uuid();

        v_step_status := CASE
            WHEN v_job.status = 'completed' THEN 'completed'
            WHEN v_job.status IN ('failed', 'permanently_failed') THEN 'failed'
            WHEN v_job.status = 'pending' THEN 'pending'
            ELSE 'in_progress'
        END;

        v_run_status := CASE
            WHEN v_step_status = 'completed' THEN 'completed'
            WHEN v_step_status = 'failed' THEN 'failed'
            WHEN v_step_status = 'pending' THEN 'pending'
            ELSE 'in_progress'
        END;

        v_operation_started_at := CASE
            WHEN v_step_status IN ('in_progress', 'completed', 'failed') THEN COALESCE(v_job.created_at, v_now)
            ELSE NULL
        END;

        v_operation_completed_at := CASE
            WHEN v_step_status IN ('completed', 'failed') THEN COALESCE(v_job.completed_at, v_now)
            ELSE NULL
        END;

        IF v_operation_started_at IS NOT NULL AND v_operation_completed_at IS NOT NULL THEN
            v_duration_ms := GREATEST(
                0,
                (EXTRACT(EPOCH FROM (v_operation_completed_at - v_operation_started_at)) * 1000)::INT
            );
        ELSE
            v_duration_ms := NULL;
        END IF;

        v_context := jsonb_strip_nulls(jsonb_build_object(
            'legacy_backfill', TRUE,
            'outbound_call_id', v_job.id,
            'call_type', v_job.call_type,
            'job_context', v_job.context
        ));

        v_step_result := jsonb_strip_nulls(jsonb_build_object(
            'outbound_call_id', v_job.id,
            'status', v_job.status,
            'response_status_code', v_job.response_status_code,
            'legacy_backfill', TRUE
        ));

        IF v_job.status = 'completed' AND v_job.response_status_code IS NOT NULL THEN
            v_step_result := v_step_result || jsonb_build_object('response_status_code', v_job.response_status_code);
        END IF;

        v_failure_reason := CASE
            WHEN v_run_status = 'failed' THEN COALESCE(v_job.error_message, 'legacy_outbound_failure')
            ELSE NULL
        END;

        v_last_error := CASE
            WHEN v_run_status = 'failed' THEN jsonb_strip_nulls(jsonb_build_object(
                'error', COALESCE(v_job.error_message, 'legacy_outbound_failure'),
                'status', v_job.status
            ))
            ELSE NULL
        END;

        INSERT INTO workflow_runs (
            id,
            workflow_template_id,
            workflow_template_version,
            entry_point,
            workflow_status,
            current_step_id,
            context,
            metadata,
            created_at,
            started_at,
            updated_at,
            completed_at,
            failure_reason,
            last_error
        )
        VALUES (
            v_run_id,
            '99990000-0000-0000-0000-000000350000',
            1,
            'legacy_bridge',
            v_run_status,
            CASE WHEN v_run_status = 'completed' THEN NULL ELSE '99990000-0000-0000-0000-000000350101'::UUID END,
            v_context,
            jsonb_build_object('legacy_backfill', TRUE),
            COALESCE(v_job.created_at, v_now),
            v_operation_started_at,
            v_now,
            CASE WHEN v_run_status IN ('completed', 'failed') THEN v_operation_completed_at ELSE NULL END,
            v_failure_reason,
            v_last_error
        );

        INSERT INTO workflow_run_steps (
            id,
            workflow_run_id,
            workflow_template_step_id,
            sequence_order,
            step_status,
            operation_name,
            max_retries,
            metadata,
            handler_key,
            handler_version,
            operation_result,
            operation_started_at,
            operation_completed_at,
            duration_ms,
            last_error,
            retry_attempt,
            enqueued_at,
            created_at,
            updated_at
        )
        VALUES (
            v_step_id,
            v_run_id,
            '99990000-0000-0000-0000-000000350101'::UUID,
            1,
            v_step_status,
            'legacy_outbound_job',
            GREATEST(v_job.max_retries, 1),
            jsonb_strip_nulls(jsonb_build_object(
                'legacy_backfill', TRUE,
                'original_status', v_job.status
            )),
            'outbound_http',
            'v1',
            v_step_result,
            v_operation_started_at,
            v_operation_completed_at,
            v_duration_ms,
            CASE WHEN v_step_status = 'failed' THEN COALESCE(v_job.error_message, 'legacy_outbound_failure') ELSE NULL END,
            GREATEST(v_job.retry_count, 1),
            COALESCE(v_job.created_at, v_now),
            COALESCE(v_job.created_at, v_now),
            v_now
        );

        UPDATE outbound_calls
        SET workflow_run_step_id = v_step_id
        WHERE id = v_job.id;
    END LOOP;
END;
$$;

COMMIT;
