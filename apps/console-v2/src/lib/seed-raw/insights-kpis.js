// insights-kpis.js — Phase F1 / CLAIM-INSIGHTS-REPORTING.
//
// Mirrors the canonical KPI catalog + daily rollups projection from
// supabase/migrations/202601311830_kpi_catalog_rollups_v1.sql:
//
//   public.kpi_definitions
//     (id, organization_id, key, name, description, unit, definition jsonb,
//      is_active, metadata jsonb, created_at, updated_at)
//     - Unique (organization_id, key); RLS: tenant-only SELECT.
//
//   public.kpi_rollups_daily
//     (id, organization_id, kpi_key, day, dimensions jsonb,
//      value_num NUMERIC | (numerator + denominator), idempotency_key,
//      metadata jsonb, created_at, updated_at)
//     - Unique (organization_id, kpi_key, day, dimensions); RLS: tenant-only.
//     - FK (organization_id, kpi_key) → kpi_definitions(organization_id, key).
//
// Capability gate is the existing `insights.read` (declared in registry.js
// capabilities array) — kept minimal so the production swap is environment-only.
//
// The 12 reporting cards rendered in `src/modules/insights/reporting.tsx` were
// previously hardcoded literals tagged `static`. This seed pins each card to a
// canonical kpi_key and supplies the latest day's rollup value so that the
// in-memory swap-seam returns the same shape the canonical RPC will return at
// cutover. The 4 group sections + ordering mirror the operator surface:
//   • Operations    : on_time_delivery_rate / exception_rate / avg_dispatch_time_minutes
//   • Marketplace   : active_partners / cod_collection_rate / dispute_rate
//   • Integrations  : webhook_delivery_rate / provider_error_rate / plugin_event_volume
//   • Workflows     : workflow_run_success_rate / manual_review_open / workflow_avg_run_seconds
//
// Tone + delta semantics live in `definition` so the FE never invents tone
// thresholds; the resolver computes tone by comparing value_num to the
// definition's `target` and `warn_below` / `warn_above` thresholds.

