#!/usr/bin/env node
/**
 * automation-pr-policy.js
 *
 * Enterprise guardrail for planless automation PRs.
 *
 * Some CI-generated PRs are administrative by nature (plan archive, branch sync).
 * These PRs may bypass `Plan:` / `Step:` requirements, but ONLY when they satisfy
 * a strict, auditable policy.
 *
 * Outputs (github-output):
 * - is_automation: 1|0
 * - kind: plan-archive|branch-retention|main-to-dev-sync|unknown
 * - policy_ok: 1|0
 * - skip_plan_checks: 1|0
 * - dependency_only: 1|0
 * - policy_path: automation|dependency_fast_lane|default
 * - policy_reason: string
 * - reason: string
 */
/* eslint-disable no-console */
const fs = require('fs');

const MARKERS = Object.freeze({
  mainToDevSync: '<!-- masarx-main-to-dev-sync -->',
  branchRetention: '<!-- masarx-automation-branch-retention -->',
  planArchive: '<!-- masarx-automation-plan-archive -->',
});
const DEPENDENCY_DEFAULT_ACTORS = Object.freeze(['dependabot[bot]']);
const DEPENDENCY_FILE_PATTERNS = Object.freeze([
  /(^|\/)package\.json$/i,
  /(^|\/)package-lock\.json$/i,
  /(^|\/)npm-shrinkwrap\.json$/i,
  /(^|\/)yarn\.lock$/i,
  /(^|\/)pnpm-lock\.ya?ml$/i,
  /(^|\/)pnpm-workspace\.ya?ml$/i,
  /(^|\/)bun\.lockb?$/i,
  /^\.github\/dependabot\.ya?ml$/i,
]);
const WORKFLOW_FILE_RE = /^\.github\/workflows\/.+\.ya?ml$/i;
const ACTIONS_USES_RE = /^uses:\s*['"]?[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+(?:\/[A-Za-z0-9_./-]+)?@[A-Za-z0-9_./-]+['"]?$/i;
const ACTIONS_DOCKER_USES_RE = /^uses:\s*['"]?docker:\/\/[^'"]+['"]?$/i;

function die(msg) {
  console.error(`[automation-pr-policy] ${msg}`);
  process.exit(1);
}

function parseArgs() {
  const argv = process.argv.slice(2);
  const out = { format: '' };
  for (let i = 0; i < argv.length; i++) {
    const a = String(argv[i] || '');
    if (!a) continue;
    if (a === '--format') out.format = String(argv[++i] || '').trim();
    else if (a.startsWith('--format=')) out.format = a.split('=').slice(1).join('=').trim();
  }
  return out;
}

function writeGithubOutput(kv) {
  const outPath = process.env.GITHUB_OUTPUT;
  if (!outPath) die('GITHUB_OUTPUT not set; run with --format json locally.');
  const lines = [];
  for (const [k, v] of Object.entries(kv)) {
    lines.push(`${k}=${String(v == null ? '' : v)}`);
  }
  fs.appendFileSync(outPath, lines.join('\n') + '\n', 'utf8');
}

function parseEnvList(raw) {
  return String(raw || '')
    .split(/[,\s]+/g)
    .map((s) => String(s || '').trim())
    .filter(Boolean);
}

function parseRepo(full) {
  const v = String(full || '').trim();
  const m = /^([^/]+)\/([^/]+)$/.exec(v);
  return m ? { owner: m[1], repo: m[2] } : { owner: '', repo: '' };
}

function normalizeTitle(s) {
  return String(s || '').trim().toLowerCase();
}

function expandActorAllowlist(actors) {
  const out = new Set();
  for (const raw of actors || []) {
    const actor = String(raw || '').trim().toLowerCase();
    if (!actor) continue;
    out.add(actor);
    const app = /^app\/([a-z0-9._-]+)$/i.exec(actor);
    if (app && app[1]) out.add(`${String(app[1]).toLowerCase()}[bot]`);
  }
  return out;
}

function isSameRepoPr(pr) {
  const headRepo = String(pr?.head?.repo?.full_name || '').trim();
  const baseRepo = String(pr?.base?.repo?.full_name || '').trim();
  if (headRepo && baseRepo) return headRepo === baseRepo;
  // Be permissive if the API response does not include repo metadata.
  return true;
}

function resolveAllowedAuthors(env) {
  const defaults = ['github-actions[bot]'];
  const extra = parseEnvList(env?.AUTOMATION_PR_ALLOWED_ACTORS || env?.AUTOMATION_PR_ALLOWED_AUTHORS || '');
  return expandActorAllowlist([...defaults, ...extra]);
}

function resolveDependencyActors(env) {
  const extra = parseEnvList(env?.DEPENDENCY_PR_ALLOWED_ACTORS || env?.DEPENDENCY_PR_ALLOWED_AUTHORS || '');
  return expandActorAllowlist([...DEPENDENCY_DEFAULT_ACTORS, ...extra]);
}

function detectAutomationKind(pr) {
  const baseRef = String(pr?.base?.ref || '').trim();
  const headRef = String(pr?.head?.ref || '').trim();
  const title = String(pr?.title || '').trim();
  const body = String(pr?.body || '');

  const hasMarkerSync = body.includes(MARKERS.mainToDevSync);
  const hasMarkerRetention = body.includes(MARKERS.branchRetention);
  const hasMarkerPlanArchive = body.includes(MARKERS.planArchive);

  const looksPlanArchive =
    headRef.startsWith('automation/plan-archive/') ||
    title.startsWith('chore: auto-archive plan(s) ') ||
    body.includes('Auto-generated by Plan Auto Archive') ||
    hasMarkerPlanArchive ||
    hasMarkerRetention;

  const looksMainToDevSync =
    baseRef === 'dev' &&
    (headRef.startsWith('automation/sync-main-to-dev/') || hasMarkerSync || normalizeTitle(title) === 'chore: sync main -> dev');

  const isCandidate = looksPlanArchive || looksMainToDevSync;
  if (!isCandidate) return { isCandidate: false, kind: 'unknown', signals: {} };

  if (looksMainToDevSync) {
    return {
      isCandidate: true,
      kind: 'main-to-dev-sync',
      signals: { hasMarkerSync, baseRef, headRef, title },
    };
  }

  if (looksPlanArchive) {
    return {
      isCandidate: true,
      kind: hasMarkerRetention ? 'branch-retention' : 'plan-archive',
      signals: { hasMarkerPlanArchive, hasMarkerRetention, baseRef, headRef, title },
    };
  }

  return { isCandidate: true, kind: 'unknown', signals: { baseRef, headRef, title } };
}

function validateAutomationPr({ pr, kind, files, allowedAuthors }) {
  const baseRef = String(pr?.base?.ref || '').trim();
  const headRef = String(pr?.head?.ref || '').trim();
  const title = String(pr?.title || '').trim();
  const body = String(pr?.body || '');

  if (!isSameRepoPr(pr)) return { ok: false, reason: 'cross_repo_pr' };
  if (baseRef !== 'dev') return { ok: false, reason: 'base_not_dev' };

  if (kind === 'main-to-dev-sync') {
    const author = String(pr?.user?.login || '').trim().toLowerCase();
    if (!allowedAuthors || allowedAuthors.size === 0) return { ok: false, reason: 'missing_allowed_authors' };
    if (!allowedAuthors.has(author)) return { ok: false, reason: `author_not_allowed:${author || '<none>'}` };
    if (!headRef.startsWith('automation/sync-main-to-dev/')) return { ok: false, reason: 'bad_head_ref' };
    if (!body.includes(MARKERS.mainToDevSync)) return { ok: false, reason: 'missing_marker' };
    if (normalizeTitle(title) !== 'chore: sync main -> dev') return { ok: false, reason: 'bad_title' };
    return { ok: true, reason: 'ok' };
  }

  if (kind === 'plan-archive' || kind === 'branch-retention') {
    if (!headRef.startsWith('automation/plan-archive/')) return { ok: false, reason: 'bad_head_ref' };

    const legacySignal =
      body.includes('Auto-generated by Plan Auto Archive') || title.startsWith('chore: auto-archive plan(s) ');
    const hasAnyMarker = body.includes(MARKERS.planArchive) || body.includes(MARKERS.branchRetention) || legacySignal;
    if (!hasAnyMarker) return { ok: false, reason: 'missing_marker' };

    const list = Array.isArray(files) ? files : [];
    if (list.length === 0) return { ok: false, reason: 'missing_files' };
    const outside = list.filter((f) => !String(f || '').startsWith('docs/ops/plans/'));
    if (outside.length) {
      const sample = outside.slice(0, 10).join(', ');
      const more = outside.length > 10 ? ` (+${outside.length - 10} more)` : '';
      return { ok: false, reason: `unsafe_files:${sample}${more}` };
    }

    return { ok: true, reason: 'ok' };
  }

  return { ok: false, reason: 'unknown_kind' };
}

function isDependencyScopedFile(file) {
  const name = String(file?.filename || file || '').trim();
  if (!name) return false;
  return DEPENDENCY_FILE_PATTERNS.some((re) => re.test(name));
}

function isWorkflowActionVersionOnlyPatch(patch) {
  const lines = String(patch || '').split('\n');
  let touched = 0;

  for (const rawLine of lines) {
    const line = String(rawLine || '');
    if (!line) continue;
    if (line.startsWith('@@') || line.startsWith('+++') || line.startsWith('---') || line.startsWith('diff --git')) continue;
    if (!(line.startsWith('+') || line.startsWith('-'))) continue;

    const value = String(line.slice(1) || '').trim();
    if (!value) continue;
    if (value.startsWith('#')) continue;

    touched += 1;
    const normalized = value.replace(/\s+#.*$/, '').trim();
    if (ACTIONS_USES_RE.test(normalized) || ACTIONS_DOCKER_USES_RE.test(normalized)) continue;
    return false;
  }

  return touched > 0;
}

function isWorkflowActionVersionOnlyFile(file) {
  const name = String(file?.filename || '').trim();
  if (!WORKFLOW_FILE_RE.test(name)) return false;
  const patch = String(file?.patch || '');
  if (!patch) return false;
  return isWorkflowActionVersionOnlyPatch(patch);
}

function detectDependencyOnlyPr({ pr, files, allowedActors }) {
  const baseRef = String(pr?.base?.ref || '').trim();
  const headRef = String(pr?.head?.ref || '').trim().toLowerCase();
  const author = String(pr?.user?.login || '').trim().toLowerCase();
  const list = Array.isArray(files) ? files : [];

  if (!isSameRepoPr(pr)) return { dependencyOnly: false, reason: 'cross_repo_pr' };
  if (baseRef !== 'dev') return { dependencyOnly: false, reason: 'base_not_dev' };
  const dependencyActor = headRef.startsWith('dependabot/') || (allowedActors && allowedActors.has(author));
  if (!dependencyActor) return { dependencyOnly: false, reason: 'actor_not_dependency_automation' };
  if (!list.length) return { dependencyOnly: false, reason: 'missing_files' };

  const unsafe = [];
  for (const file of list) {
    if (isDependencyScopedFile(file)) continue;
    if (isWorkflowActionVersionOnlyFile(file)) continue;
    const name = String(file?.filename || '').trim();
    if (name) unsafe.push(name);
  }

  if (unsafe.length) {
    const sample = unsafe.slice(0, 10).join(', ');
    const more = unsafe.length > 10 ? ` (+${unsafe.length - 10} more)` : '';
    return { dependencyOnly: false, reason: `unsafe_files:${sample}${more}` };
  }

  return { dependencyOnly: true, reason: 'ok' };
}

async function ghRequestJson({ token, url }) {
  const t = String(token || '').trim();
  if (!t) throw new Error('GITHUB_TOKEN is missing');
  const res = await fetch(String(url || '').trim(), {
    method: 'GET',
    headers: {
      accept: 'application/vnd.github+json',
      authorization: `Bearer ${t}`,
      'user-agent': 'masarx-automation-pr-policy',
    },
  });
  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`GitHub API ${res.status} for ${url}: ${text || res.statusText}`);
  }
  return res.json();
}

async function fetchPullRequest({ owner, repo, prNumber, token }) {
  const url = `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${prNumber}`;
  return ghRequestJson({ token, url });
}

async function listPullRequestFilesDetailed({ owner, repo, prNumber, token }) {
  const files = [];
  let page = 1;
  while (true) {
    // eslint-disable-next-line no-await-in-loop
    const data = await ghRequestJson({
      token,
      url: `https://api.github.com/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}/pulls/${prNumber}/files?per_page=100&page=${page}`,
    });
    const batch = Array.isArray(data) ? data : [];
    for (const f of batch) {
      const name = String(f?.filename || '').trim();
      if (!name) continue;
      files.push({
        filename: name,
        status: String(f?.status || '').trim(),
        patch: typeof f?.patch === 'string' ? f.patch : '',
      });
    }
    if (batch.length < 100) break;
    page += 1;
  }
  return files;
}

function readEventJson() {
  const evtPath = process.env.GITHUB_EVENT_PATH;
  if (!evtPath || !fs.existsSync(evtPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(evtPath, 'utf8'));
  } catch {
    return null;
  }
}

function resolvePrNumberFromContext(evt) {
  const envN = parseInt(String(process.env.PR_NUMBER || '').trim(), 10);
  if (Number.isFinite(envN) && envN > 0) return envN;
  const n = parseInt(String(evt?.pull_request?.number || evt?.number || '').trim(), 10);
  if (Number.isFinite(n) && n > 0) return n;
  return 0;
}

async function main() {
  const { format } = parseArgs();
  const fmt = String(format || '').trim().toLowerCase();

  const evt = readEventJson() || {};
  const prNumber = resolvePrNumberFromContext(evt);
  const repoFull = String(process.env.GITHUB_REPOSITORY || '').trim();
  const token = String(process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '').trim();

  const outBase = {
    is_automation: '0',
    kind: 'unknown',
    policy_ok: '0',
    skip_plan_checks: '0',
    dependency_only: '0',
    policy_path: 'default',
    policy_reason: 'not_automation',
    reason: 'not_automation',
  };

  if (!prNumber || !repoFull.includes('/')) {
    if (fmt === 'github-output') writeGithubOutput(outBase);
    else process.stdout.write(JSON.stringify(outBase, null, 2) + '\n');
    return;
  }

  const { owner, repo } = parseRepo(repoFull);
  if (!owner || !repo || !token) {
    // Unable to evaluate policy; fall back to normal plan enforcement.
    if (fmt === 'github-output') writeGithubOutput(outBase);
    else process.stdout.write(JSON.stringify(outBase, null, 2) + '\n');
    return;
  }

  let pr;
  try {
    pr = await fetchPullRequest({ owner, repo, prNumber, token });
  } catch (e) {
    console.warn(`[automation-pr-policy] Unable to fetch PR #${prNumber}: ${e.message}`);
    if (fmt === 'github-output') writeGithubOutput(outBase);
    else process.stdout.write(JSON.stringify(outBase, null, 2) + '\n');
    return;
  }

  const detected = detectAutomationKind(pr);
  const allowedAuthors = resolveAllowedAuthors(process.env);
  const allowedDependencyActors = resolveDependencyActors(process.env);

  let filesDetailed = [];
  try {
    filesDetailed = await listPullRequestFilesDetailed({ owner, repo, prNumber, token });
  } catch (e) {
    console.warn(`[automation-pr-policy] Unable to list PR files for #${prNumber}: ${e.message}`);
  }
  const files = filesDetailed.map((entry) => String(entry?.filename || '').trim()).filter(Boolean);
  const dependencyVerdict = detectDependencyOnlyPr({
    pr,
    files: filesDetailed,
    allowedActors: allowedDependencyActors,
  });

  if (detected.isCandidate && detected.kind !== 'unknown') {
    const verdict = validateAutomationPr({ pr, kind: detected.kind, files, allowedAuthors });
    if (!verdict.ok) {
      die(`Automation PR policy failed (${detected.kind}): ${verdict.reason}`);
    }

    const out = {
      ...outBase,
      is_automation: '1',
      kind: detected.kind,
      policy_ok: '1',
      skip_plan_checks: '1',
      policy_path: 'automation',
      policy_reason: 'automation_plan_bypass',
      reason: 'ok',
    };
    if (fmt === 'github-output') writeGithubOutput(out);
    else process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    return;
  }

  if (dependencyVerdict.dependencyOnly) {
    const out = {
      ...outBase,
      policy_ok: '1',
      dependency_only: '1',
      policy_path: 'dependency_fast_lane',
      policy_reason: 'dependency_only',
      reason: 'dependency_only',
    };
    if (fmt === 'github-output') writeGithubOutput(out);
    else process.stdout.write(JSON.stringify(out, null, 2) + '\n');
    return;
  }

  const out = {
    ...outBase,
    is_automation: detected.isCandidate ? '1' : '0',
    reason: detected.isCandidate ? 'unknown_kind' : 'not_automation',
    policy_reason:
      detected.isCandidate
        ? 'unknown_automation_kind'
        : (dependencyVerdict.reason || 'not_automation'),
  };

  if (fmt === 'github-output') writeGithubOutput(out);
  else process.stdout.write(JSON.stringify(out, null, 2) + '\n');
}

if (require.main === module) {
  // eslint-disable-next-line promise/catch-or-return
  main().catch((e) => die(e && e.message ? e.message : String(e)));
}

module.exports = {
  MARKERS,
  parseEnvList,
  parseRepo,
  normalizeTitle,
  isSameRepoPr,
  resolveAllowedAuthors,
  resolveDependencyActors,
  isDependencyScopedFile,
  isWorkflowActionVersionOnlyPatch,
  isWorkflowActionVersionOnlyFile,
  detectDependencyOnlyPr,
  detectAutomationKind,
  validateAutomationPr,
};
