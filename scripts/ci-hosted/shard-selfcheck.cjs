'use strict';
const assert = require('node:assert/strict');
const { parseEntries, retainedEntries, expectedForFiles, shardOption, evaluate, identity } = require('./jest.cjs');
const file = 'tests/unit/synthetic.test.js'; const other = 'tests/unit/other.test.js';
const id = identity(file, 'case'); const otherId = identity(other, 'other');
const entries = parseEntries(`unit\t${file}\t${id}\nunit\t${other}\t${otherId}\n`, 'unit');
assert.deepEqual(expectedForFiles(entries, [file, other], [file]), new Set([id]));
assert.deepEqual(expectedForFiles(entries, [file, other], [other]), new Set([otherId]));
for (const selected of [[], [file, file], ['tests/unit/missing.test.js']]) assert.throws(() => expectedForFiles(entries, [file, other], selected));
assert.throws(() => expectedForFiles(entries, [file], [file]));
assert.throws(() => expectedForFiles(parseEntries(`unit\t${id}`, 'unit'), [file], [file]));
assert.throws(() => parseEntries(`unit\ttests/unit/../escape.js\t${id}`, 'unit'));
for (const value of ['0/8', '9/8', '1/65', '1/2 extra']) assert.throws(() => shardOption(value));
assert.equal(shardOption('1/8'), '1/8'); assert.equal(shardOption(), null);
assert.deepEqual(retainedEntries(entries, new Map([[id, file]])), new Map([[id, file]]));
assert.equal(retainedEntries(new Map(), entries).size, 0);
assert.equal(retainedEntries(entries, new Map([[id, other]])).size, 0);
const report = status => ({ testResults: [{ name: require('node:path').resolve(file), status, assertionResults: [{ fullName: 'case', status }] }] });
assert.equal(evaluate(report('failed'), new Set([id]), 1, process.cwd()).ok, true);
assert.equal(evaluate(report('passed'), new Set([id]), 0, process.cwd()).ok, false);
console.log('PASS: shard selection, missing baselines, invalid shards and stale failures');
