"""Render the base-owned policy workflow from its canonical source selector."""
from pathlib import Path
import re


def render(root):
    policy = (root / 'scripts/ci-hosted/policy.cjs').read_text(encoding='utf-8')
    selector = re.search(r'^const sha = value => \{.*?^\};\nfunction policySource\(event, kind\) \{.*?^\}', policy, re.M | re.S).group()
    resolve = "const fs = require('node:fs');\n" + selector + "\n" + """const event = JSON.parse(fs.readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
const base = policySource(event, process.env.GITHUB_EVENT_NAME);
fs.appendFileSync(process.env.GITHUB_OUTPUT, `base=${base}\\n`);
"""
    header = """# Generated by scripts/ci-hosted/render-policy.py; edit the canonical helpers and regenerate.
name: Required repository policy

'on':
  pull_request_target:
    branches: [preview, dev, main]
  merge_group:
    branches: [preview, dev, main]
    types: [checks_requested]

permissions:
  contents: read

env:
  NPM_CONFIG_IGNORE_SCRIPTS: 'true'

concurrency:
  group: required-policy-${{ github.run_id }}
  cancel-in-progress: false

jobs:
  policy:
    name: Required repository policy
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    steps:
      - uses: actions/setup-node@53b83947a5a98c8d113130e565377fae1a50d02f # frozen version: 53b83947a5a98c8d113130e565377fae1a50d02f (Node24)
        with:
          node-version: '24.22.1'
          package-manager-cache: false
      - name: Resolve the trusted target base
        id: source
        shell: bash
        run: |
          node <<'NODE'
"""
    footer = """          NODE
      - uses: actions/checkout@de0fac2e4500dabe0009e67214ff5f5447ce83dd # frozen version: de0fac2e4500dabe0009e67214ff5f5447ce83dd (Node24)
        with:
          ref: ${{ steps.source.outputs.base }}
          persist-credentials: false
          fetch-depth: 2
          sparse-checkout: scripts/ci-hosted
      - name: Enforce the target-base guard without executing candidate code
        run: node scripts/ci-hosted/policy.cjs
"""
    return header + ''.join('          ' + line + '\n' for line in resolve.splitlines()) + footer


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    (root / '.github/workflows/policy.yml').write_text(render(root), encoding='utf-8', newline='\n')
