"""Render trusted inline policy logic; never fetches or executes candidate code."""
from pathlib import Path
import re


def render(root):
    helpers = root / 'scripts/ci-hosted'

    def body(name):
        text = (helpers / name).read_text(encoding='utf-8')
        text = re.sub(r'^const .* = require\(\'\./(?:target-policy|migrations|install-policy)\.cjs\'\);\n', '', text, flags=re.M)
        text = re.sub(r'^if \(require.main === module\).*\n', '', text, flags=re.M)
        return re.sub(r'^module.exports = .*\n', '', text, flags=re.M).strip()

    target = body('target-policy.cjs').replace('{ encoding, input, timeout:', '{ cwd: policyDir, encoding, input, timeout:')
    migration = body('migrations.cjs')
    policy = body('policy.cjs')
    install = body('install-policy.cjs')
    code = r'''const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const repository = process.env.GITHUB_REPOSITORY || '';
if (!/^[a-zA-Z0-9_.-]+\/[a-zA-Z0-9_.-]+$/.test(repository)) throw new Error('Invalid target repository');
const policyDir = fs.mkdtempSync(path.join(os.tmpdir(), 'required-policy-'));
try {
  for (const args of [['init', '--bare'], ['remote', 'add', 'origin', `https://github.com/${repository}.git`]]) {
    const result = spawnSync('git', ['-c', 'core.hooksPath=/dev/null', ...args], { cwd: policyDir, stdio: 'ignore', timeout: 120000 });
    if (result.error || result.status !== 0) throw new Error('Cannot initialize policy object store');
  }
'''
    code += '  const targetPolicy = (() => {\n' + target + '\nreturn { git, targetBase, targetFile };\n})();\n'
    code += '  const migrationPolicy = (() => {\nconst { git, targetFile } = targetPolicy;\n' + migration + '\nreturn { assess, exceptions, objectsAt };\n})();\n'
    code += '  const installPolicy = (() => {\n' + install + '\nreturn { checkInstallPolicy };\n})();\n'
    code += '  const requiredPolicy = (() => {\nconst { git, targetFile } = targetPolicy;\nconst { assess, exceptions, objectsAt } = migrationPolicy;\nconst { checkInstallPolicy } = installPolicy;\n' + policy + '\nreturn { main };\n})();\n'
    code += '''  requiredPolicy.main();
} catch (error) { console.error(error.message); process.exitCode = 1; }
finally { fs.rmSync(policyDir, { recursive: true, force: true }); }
'''
    header = '''# Generated by scripts/ci-hosted/render-policy.py; edit the canonical helpers and regenerate.
name: Required repository policy

'on':
  pull_request:
  pull_request_target:
  merge_group:
    types: [checks_requested]

permissions:
  contents: read

env:
  NPM_CONFIG_IGNORE_SCRIPTS: 'true'

concurrency:
  group: required-policy-${{ github.run_id }}
  cancel-in-progress: false

jobs:
  policy:
    name: Required repository policy
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    steps:
      - uses: actions/setup-node@53b83947a5a98c8d113130e565377fae1a50d02f # frozen version: 53b83947a5a98c8d113130e565377fae1a50d02f (Node24)
        with:
          node-version: '24.22.1'
          package-manager-cache: false
      - name: Enforce policy using fetched Git objects without checking out any repository code
        shell: bash
        run: |
          node <<'NODE'
'''
    return header + ''.join('          ' + line + '\n' for line in code.splitlines()) + '          NODE\n'


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    (root / '.github/workflows/policy.yml').write_text(render(root), encoding='utf-8', newline='\n')
